import assert from 'node:assert/strict';

// Issue #410の入力契約の退行検査。意味の十分性と実モデルの遵守は独立評価で扱う。
// 全文snapshotにはせず、利用例の段落内で条件と行為の結び付きを照合する。
export function expectCallerFirstInstructions(prompt: string, role: 'repair' | 'review') {
  const instructions = prompt.split(/要求:|ホストコンテキスト:/)[0] ?? '';
  const paragraph = instructions
    .split('\n')
    .find((line) => line.includes('caller-first-design.md'));
  assert(paragraph, '利用例の共通指示が必要です');
  const rules: [string, RegExp][] =
    role === 'repair'
      ? [
          ['構造選択前の具体化', /構造[^。]*前に[^。]*(?:利用例|例)[^。]*(?:示|具体化)/u],
          ['呼出元の利用条件', /呼出元[^。]*入力[^。]*操作[^。]*期待(?:する)?結果/u],
          ['判断を変える終了条件', /失敗[^。]*取消[^。]*所有[^。]*終了/u],
          ['既存例と今回の判断の対応', /既存(?:の)?例[^。]*今回[^。]*対応/u],
          ['既存の途中記録', /例[^。]*進捗説明[^。]*(?:残|記録)/u],
          ['実装後の照合', /実装後[^。]*例[^。]*照合/u],
          [
            '後付けを事前の証拠にしない',
            /(?:後から|後付け)[^。]*例[^。]*事前[^。]*証拠[^。]*(?:せず|しない)/u,
          ],
          [
            '適用外へ工程を強制しない',
            /(?:内部変更|文書修正)[^。]*一律[^。]*(?:要求しない|増やさず)/u,
          ],
          ['人への戻り先', /(?:要求|公開契約)[^。]*権限[^。]*人へ/u],
          ['独立テストへの戻り先', /検証資産[^。]*独立テスト/u],
        ]
      : [
          [
            '対応と順序を分ける',
            /例[^。]*(?:設計|実装)[^。]*(?:前に|順序)[^。]*証拠[^。]*分けて[^。]*確認/u,
          ],
          ['対象版の記録を照合する', /対象版[^。]*(?:参照可能|参照できる)[^。]*記録/u],
          [
            '本文取得や成功だけでは順序を確認しない',
            /本文取得[^。]*テスト[^。]*最終findings[^。]*(?:確認したとしない|証拠にしない)/u,
          ],
          ['順序不明を未確認とする', /(?:記録がな|順序[^。]*確認できない)[^。]*未確認/u],
          ['非公開の思考を推測しない', /非公開[^。]*思考[^。]*推測しない/u],
          ['不一致を条件と影響付きで戻す', /不一致[^。]*条件[^。]*影響[^。]*指摘へ/u],
          [
            '適用外と独立した期待値を保つ',
            /適用外[^。]*工程[^。]*独立テスト[^。]*期待値[^。]*(?:しない|せず)/u,
          ],
        ];
  for (const [condition, pattern] of rules) {
    assert(pattern.test(paragraph), `${role}: ${condition}の指示が不足しています`);
  }
}
